export async function catalog(fetcher = fetch) {
  if (Date.now() - refreshed > 60000) {
    refreshTask ??= (async () => {
      try {
        const r = await fetcher(INDEX_URL, { signal: AbortSignal.timeout(5000) });
        if (!r.ok) throw new Error('Index unavailable');
        const data = await r.json();
        if (!Array.isArray(data.stickers) || !data.stickers.length || !data.stickers.every(validSticker)) throw new Error('Invalid catalog');
        cached = data.stickers;
      } catch { /* Retain the last valid catalog during upstream outages. */ }
      refreshed = Date.now();
    })().finally(() => { refreshTask = undefined; });
    await refreshTask;
  }
  return cached;
}
export function choose(stickers, args) {
  if (args.stickerId) return stickers.find(s => s.id === args.stickerId);
  const query = (args.query || '').toLowerCase();
  const scored = stickers.map(s => ({ s, score: [s.name, ...s.emotion_tags, ...s.chat_scenarios].reduce((sum, t) => sum + (query.includes(t.toLowerCase()) ? 5 : 0) + (t.length > 1 && t.toLowerCase().includes(query) && query ? 2 : 0), 0) }));
  const highest = Math.max(...scored.map(x => x.score));
  const candidates = scored.filter(x => x.score === highest);
  return candidates[Math.floor(Math.random() * candidates.length)]?.s;
}

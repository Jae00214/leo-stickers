  const id = message?.id ?? null;
  const reply = result => Response.json({ jsonrpc: '2.0', id, result });
  const error = (code, text) => Response.json({ jsonrpc: '2.0', id, error: { code, message: text } });
  if (!message || message.jsonrpc !== '2.0' || typeof message.method !== 'string') return error(-32600, 'Invalid request');
